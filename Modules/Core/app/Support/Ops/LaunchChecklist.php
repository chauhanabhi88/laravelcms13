<?php

declare(strict_types=1);

namespace Modules\Core\Support\Ops;

use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Route;
use Illuminate\Support\Facades\Storage;
use Modules\Core\Support\Security\ContentSecurityPolicy;
use Throwable;

/**
 * Go-live preflight (plan M21 S7, §9, §11): configuration that must be right before real
 * customers arrive. "fail" blocks the launch, "warn" needs a conscious decision.
 */
class LaunchChecklist
{
    public const PASS = 'pass';

    public const WARN = 'warn';

    public const FAIL = 'fail';

    /**
     * @return list<array{check: string, status: string, detail: string}>
     */
    public function run(): array
    {
        $checks = [];
        $add = function (string $check, bool $ok, string $detail, string $severity = self::FAIL) use (&$checks): void {
            $checks[] = ['check' => $check, 'status' => $ok ? self::PASS : $severity, 'detail' => $detail];
        };

        $add('APP_ENV is production', app()->isProduction(), 'APP_ENV='.app()->environment());
        $add('APP_DEBUG is off', ! config('app.debug'), 'Debug pages leak code and secrets.');
        $add('APP_KEY is set', filled(config('app.key')), 'php artisan key:generate (keep the old key in APP_PREVIOUS_KEYS when rotating).');
        $add('APP_URL uses https', str_starts_with((string) config('app.url'), 'https://'), 'APP_URL='.config('app.url'));
        $add('Session cookie is secure', (bool) config('session.secure'), 'SESSION_SECURE_COOKIE=true');
        $add('Configuration is cached', app()->configurationIsCached(), 'php artisan optimize', self::WARN);
        $add('Routes are cached', app()->routesAreCached(), 'php artisan optimize', self::WARN);

        $add('Queue is asynchronous', ! in_array(config('queue.default'), ['sync', 'null'], true), 'QUEUE_CONNECTION='.config('queue.default'));
        $add('Cache store is shared and flushable', in_array(config('cache.default'), ['file', 'redis', 'memcached'], true), 'CACHE_STORE='.config('cache.default'));
        $add('Mail is really sent', ! in_array(config('mail.default'), ['log', 'array'], true), 'MAIL_MAILER='.config('mail.default'));
        $add('SMS gateway is live', ! in_array(config('core.sms.driver'), ['log', 'fake'], true), 'SMS_DRIVER='.config('core.sms.driver'));
        $add('Push driver is live', config('notification.push.driver') !== 'log', 'PUSH_DRIVER='.config('notification.push.driver'), self::WARN);
        $add('Prepaid gateway is Razorpay', config('payment.default_gateway') === 'razorpay', 'PAYMENT_DEFAULT_GATEWAY='.config('payment.default_gateway'));
        $add('Razorpay live keys', str_starts_with((string) config('payment.razorpay.key_id'), 'rzp_live_') && filled(config('payment.razorpay.webhook_secret')), 'RAZORPAY_KEY_ID / RAZORPAY_WEBHOOK_SECRET');
        $add('Shiprocket credentials', filled(config('logistics.shiprocket.email')) && filled(config('logistics.shiprocket.password')), 'SHIPROCKET_EMAIL / SHIPROCKET_PASSWORD', self::WARN);

        $add('Passport keys exist', is_file(storage_path('oauth-private.key')) && is_file(storage_path('oauth-public.key')), 'php artisan passport:keys');
        // file_exists(): PHP sees a Windows junction as neither a link nor a directory.
        $add('Public storage is linked', file_exists(public_path('storage')), 'php artisan storage:link');
        $add('Front-end assets are built', is_file(public_path('build/manifest.json')), 'npm ci && npm run build');
        $add('Vite dev server is not in use', ! is_file(public_path('hot')), 'Delete public/hot.');
        $add('No static robots.txt', ! is_file(public_path('robots.txt')), '/robots.txt is generated by the Storefront module.');
        $add('Crawlers are allowed', ! config('storefront.seo.robots_block_all'), 'ROBOTS_BLOCK_ALL=false');
        $add('Sitemap is generated', Storage::disk('local')->exists(trim((string) config('storefront.seo.sitemap_path', 'sitemaps'), '/').'/sitemap.xml'), 'php artisan storefront:sitemap', self::WARN);
        $add('Styleguide is not public', ! Route::has('theme.styleguide'), 'Only registered in the local environment.');

        $add('Security headers are on', (bool) config('core.security.headers'), 'SECURITY_HEADERS=true');
        $add('HSTS is on', (bool) config('core.security.hsts.enabled'), 'SECURITY_HSTS=true');
        $add('CSP is enforced', ContentSecurityPolicy::mode() === ContentSecurityPolicy::MODE_ENFORCE, 'CSP_MODE='.ContentSecurityPolicy::mode().' (enforce after two weeks without violations)', self::WARN);
        $add('Admin idle timeout', (int) config('core.security.admin_idle_minutes') > 0 && (int) config('core.security.admin_idle_minutes') <= 30, 'ADMIN_IDLE_TIMEOUT='.config('core.security.admin_idle_minutes'), self::WARN);
        $add('Admin access is restricted', config('core.security.backend_ip_allowlist') !== [], 'BACKEND_IP_ALLOWLIST, or an allowlist / 2FA at the web server', self::WARN);

        $failed = $this->failedJobs();
        $add('No failed jobs', $failed === 0, $failed === null ? 'failed_jobs table missing' : "{$failed} failed job(s): php artisan queue:failed", self::WARN);

        return $checks;
    }

    /**
     * @param  list<array{check: string, status: string, detail: string}>  $checks
     */
    public static function passes(array $checks): bool
    {
        return ! in_array(self::FAIL, array_column($checks, 'status'), true);
    }

    protected function failedJobs(): ?int
    {
        try {
            return DB::table((string) config('queue.failed.table', 'failed_jobs'))->count();
        } catch (Throwable) {
            return null;
        }
    }
}
